export function medicalClinicJsonLd() {
  const { contact, doctor } = siteConfig;
  return {
    '@context': 'https://schema.org',
    '@type': 'MedicalClinic',
    '@id': `${absoluteUrl('/')}#clinic`,
    name: siteConfig.name,
    description: siteConfig.description,
    url: absoluteUrl('/'),
    image: absoluteUrl('/opengraph-image'),
    telephone: contact.phoneHref.replace('tel:', ''),
    email: contact.email,
    address: {
      '@type': 'PostalAddress',
      streetAddress: contact.address.street,
      addressLocality: contact.address.city,
      addressRegion: contact.address.region,
      postalCode: contact.address.postalCode,
      addressCountry: contact.address.country,
    },
    openingHoursSpecification: contact.openingHours.map((h) => ({
      '@type': 'OpeningHoursSpecification',
      dayOfWeek: h.days,
      opens: h.opens,
      closes: h.closes,
    })),
    employee: {
      '@type': 'Physician',
      name: doctor.name,
    },
  };
}

export interface Crumb {
  name: string;
  /** Path starting with "/". Omit for the current page. */
  href?: string;
}

export function breadcrumbJsonLd(crumbs: Crumb[], currentPath: string) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: crumbs.map((crumb, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.href ?? currentPath),
    })),
  };
}
